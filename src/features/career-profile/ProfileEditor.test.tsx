import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, it, vi } from 'vitest'
import { ProfileEditor } from './ProfileEditor'

afterEach(() => vi.unstubAllGlobals())
const profile = { facts: [{ category: 'skills', text: 'Python', evidence: 'Python' }], preferences: { target_roles: '', locations: '', remote: 'unspecified', exclusions: '' }, revision: 1, confirmed_at: null }
it('generates a draft then saves explicit confirmation and preferences', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce({ ok: true, json: async () => null })
    .mockResolvedValueOnce({ ok: true, json: async () => profile })
    .mockResolvedValueOnce({ ok: true, json: async () => ({ ...profile, revision: 2, confirmed_at: '2026-10-29T00:00:00Z' }) })
  vi.stubGlobal('fetch', fetcher)
  render(<ProfileEditor resumeId="one" source="Python experience" />)
  const user = userEvent.setup()
  await user.click(await screen.findByRole('button', { name: 'Generate profile' }))
  await user.type(await screen.findByLabelText('Target roles'), 'Backend engineer')
  await user.click(screen.getByRole('button', { name: 'Confirm profile' }))
  await screen.findByText('Profile confirmed and saved.')
  const sent = JSON.parse(fetcher.mock.calls[2][1].body)
  expect(sent.confirm).toBe(true)
  expect(sent.preferences.target_roles).toBe('Backend engineer')
})
it('blocks unsupported quotes and retains edits when saving fails', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce({ ok: true, json: async () => profile })
    .mockResolvedValueOnce({ ok: false, status: 409, json: async () => ({ detail: 'Profile changed. Reload.' }) })
  vi.stubGlobal('fetch', fetcher)
  render(<ProfileEditor resumeId="one" source="Python experience" />)
  const user = userEvent.setup()
  const quote = await screen.findByLabelText('Supporting resume quote')
  await user.clear(quote)
  await user.type(quote, 'Java')
  expect(screen.getByRole('button', { name: 'Confirm profile' })).toBeDisabled()
  await user.clear(quote)
  await user.type(quote, 'Python')
  await user.type(screen.getByLabelText('Target roles'), 'Backend')
  await user.click(screen.getByRole('button', { name: 'Save draft' }))
  await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('Profile changed. Reload.'))
  expect(screen.getByLabelText('Target roles')).toHaveValue('Backend')
})
it('explains failed generation and offers source inspection and retry', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce({ ok: true, json: async () => null })
    .mockResolvedValueOnce({ ok: false, status: 502, json: async () => ({ detail: 'Unmatched evidence.' }) })
    .mockResolvedValueOnce({ ok: true, json: async () => profile })
  vi.stubGlobal('fetch', fetcher)
  render(<ProfileEditor resumeId="one" source="Python experience" />)
  const user = userEvent.setup()
  await user.click(await screen.findByRole('button', { name: 'Generate profile' }))
  await screen.findByText('We couldn’t create a verified profile')
  expect(screen.getByRole('alert')).toHaveTextContent('No new profile was saved')
  await user.click(screen.getByRole('button', { name: 'Inspect resume text' }))
  expect(screen.getByText('Python experience')).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Try generating again' }))
  await screen.findByLabelText('Target roles')
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
})
