import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, it, vi } from 'vitest'
import { ApplicationWorkspaces } from './ApplicationWorkspaces'

afterEach(() => vi.unstubAllGlobals())
const workspace = { id: 'w1', company: 'Example', role: 'Engineer', description: 'Build APIs', url: '', profile_snapshot: { profile_revision: 2 }, drafts: [], findings: [], reminders: [], runs: [] }
const response = (value: unknown) => ({ ok: true, json: async () => value })
it('opens a persisted workspace and saves a new draft', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(response([workspace])).mockResolvedValueOnce(response([]))
    .mockResolvedValueOnce(response(workspace)).mockResolvedValueOnce(response({ id: 'draft' }))
    .mockResolvedValueOnce(response({ ...workspace, drafts: [{ id: 'draft', kind: 'cover_letter', content: 'My draft', profile_snapshot_id: 'snapshot' }] }))
  vi.stubGlobal('fetch', fetcher)
  render(<ApplicationWorkspaces />)
  const user = userEvent.setup()
  await user.click(await screen.findByRole('button', { name: 'Example · Engineer' }))
  await screen.findByText(/Profile version 2/)
  await user.click(screen.getByRole('tab', { name: 'Draft history' }))
  await user.type(screen.getByLabelText('New draft version'), 'My draft')
  await user.click(screen.getByRole('button', { name: 'Save draft version' }))
  await screen.findByText('New draft version saved.')
  expect(JSON.parse(fetcher.mock.calls[3][1].body).content).toBe('My draft')
  expect(screen.getByLabelText('New draft version')).toHaveValue('')
})
it('keeps draft text after a failed save', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(response([workspace])).mockResolvedValueOnce(response([]))
    .mockResolvedValueOnce(response(workspace)).mockResolvedValueOnce({ ok: false, status: 503, json: async () => ({ detail: 'Backend unavailable. Retry.' }) })
  vi.stubGlobal('fetch', fetcher)
  render(<ApplicationWorkspaces />)
  const user = userEvent.setup()
  await user.click(await screen.findByRole('button', { name: 'Example · Engineer' }))
  await user.click(await screen.findByRole('tab', { name: 'Draft history' }))
  await user.type(await screen.findByLabelText('New draft version'), 'Keep this draft')
  await user.click(screen.getByRole('button', { name: 'Save draft version' }))
  await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('Backend unavailable. Retry.'))
  expect(screen.getByLabelText('New draft version')).toHaveValue('Keep this draft')
})

it('filters and expands the workspace library without opening unrelated applications', async () => {
  const items = Array.from({ length: 8 }, (_, i) => ({ ...workspace, id: `w${i}`, company: `Company ${i}`, profile_revision: i % 2 + 1 }))
  const fetcher = vi.fn().mockResolvedValueOnce(response(items)).mockResolvedValueOnce(response([]))
  vi.stubGlobal('fetch', fetcher)
  const { container } = render(<ApplicationWorkspaces />)
  const user = userEvent.setup()
  await screen.findByRole('button', { name: 'Show more workspaces (2 more)' })
  expect(container.querySelectorAll('.workspace-choice')).toHaveLength(6)
  await user.click(screen.getByRole('button', { name: 'Show more workspaces (2 more)' }))
  expect(container.querySelectorAll('.workspace-choice')).toHaveLength(8)
  await user.selectOptions(screen.getByLabelText('Profile version'), '2')
  expect(container.querySelectorAll('.workspace-choice')).toHaveLength(4)
  await user.type(screen.getByLabelText('Find company or role'), 'Company 3')
  expect(container.querySelectorAll('.workspace-choice')).toHaveLength(1)
  expect(fetcher).toHaveBeenCalledTimes(2)
})

it('retains unsaved draft text across tabs and cancels a workspace change', async () => {
  const other = { ...workspace, id: 'w2', company: 'Other' }
  const fetcher = vi.fn().mockResolvedValueOnce(response([workspace, other])).mockResolvedValueOnce(response([])).mockResolvedValueOnce(response(workspace))
  vi.stubGlobal('fetch', fetcher)
  const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
  render(<ApplicationWorkspaces />)
  const user = userEvent.setup()
  await user.click(await screen.findByRole('button', { name: 'Example · Engineer' }))
  await user.click(await screen.findByRole('tab', { name: 'Draft history' }))
  await user.type(screen.getByLabelText('New draft version'), 'Keep my unsaved text')
  await user.click(screen.getByRole('tab', { name: 'Employer form' }))
  expect(screen.getByLabelText('New draft version')).not.toBeVisible()
  await user.click(screen.getByRole('tab', { name: 'Draft history' }))
  expect(screen.getByLabelText('New draft version')).toHaveValue('Keep my unsaved text')
  await user.click(screen.getByRole('button', { name: 'Other · Engineer' }))
  expect(confirm).toHaveBeenCalled()
  expect(fetcher).toHaveBeenCalledTimes(3)
  expect(screen.getByRole('button', { name: 'Example · Engineer' })).toHaveAttribute('aria-pressed', 'true')
  confirm.mockRestore()
})

it('creates a workspace from the collapsed add-job form', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(response([])).mockResolvedValueOnce(response([{ id: 'resume', filename: 'Resume.pdf' }])).mockResolvedValueOnce(response(workspace)).mockResolvedValueOnce(response(workspace)).mockResolvedValueOnce(response([workspace]))
  vi.stubGlobal('fetch', fetcher)
  render(<ApplicationWorkspaces />)
  const user = userEvent.setup()
  await user.click(await screen.findByRole('button', { name: 'Add a job' }))
  await user.selectOptions(screen.getByLabelText('Confirmed resume profile'), 'resume')
  await user.type(screen.getByLabelText('Company', { exact: true }), 'Example')
  await user.type(screen.getByLabelText('Role', { exact: true }), 'Engineer')
  await user.type(screen.getByLabelText('Job description', { exact: true }), 'Build APIs')
  await user.click(screen.getByRole('button', { name: 'Create workspace' }))
  await screen.findByText('Workspace saved with a snapshot of your confirmed profile.')
  expect(JSON.parse(fetcher.mock.calls[2][1].body)).toMatchObject({ company: 'Example', role: 'Engineer', description: 'Build APIs', resume_id: 'resume' })
  expect(screen.getByRole('tab', { name: 'Review' })).toHaveAttribute('aria-selected', 'true')
})
