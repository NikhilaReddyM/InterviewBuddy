import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it } from 'vitest'
import { WeeklyPlanner } from './WeeklyPlanner'
import { DataProvider } from '../../app/DataProvider'
import { loadData } from '../../storage/storage'
import { calendarDate, getWeekStart, addDays } from '../../utils/dates'

beforeEach(() => {
  localStorage.clear()
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', '') }
  HTMLDialogElement.prototype.close = function () { this.removeAttribute('open') }
})
const renderPlanner = () => render(<DataProvider><WeeklyPlanner /></DataProvider>)
const summary = () => within(screen.getByLabelText('Weekly summary'))
async function addSession(topic = 'Graphs') {
  const user = userEvent.setup()
  await user.click(screen.getByRole('button', { name: 'Add session' }))
  await user.type(screen.getByLabelText('Topic'), topic)
  await user.click(screen.getByRole('button', { name: 'Save session' }))
}

describe('weekly planner', () => {
  it('creates, edits, completes, edits completion, undoes, and deletes with persisted totals', async () => {
    const user = userEvent.setup()
    const app = renderPlanner()
    await addSession()
    expect(summary().getByText('60')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Edit session' }))
    await user.clear(screen.getByLabelText('Topic'))
    await user.type(screen.getByLabelText('Topic'), 'Trees')
    await user.click(screen.getByRole('button', { name: 'Save session' }))
    expect(screen.getByRole('article', { name: 'Trees' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Mark complete' }))
    await user.clear(screen.getByLabelText('Actual minutes'))
    await user.type(screen.getByLabelText('Actual minutes'), '75')
    await user.selectOptions(screen.getByLabelText('Confidence'), '4')
    await user.type(screen.getByLabelText('Takeaways (optional)'), 'Review traversal')
    await user.click(screen.getByRole('button', { name: 'Save completion' }))
    expect(summary().getByText('75')).toBeInTheDocument()
    expect(summary().getByText('1 / 1')).toBeInTheDocument()
    app.unmount()
    renderPlanner()
    expect(screen.getByText('Review traversal')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Edit completion' }))
    await user.clear(screen.getByLabelText('Actual minutes'))
    await user.type(screen.getByLabelText('Actual minutes'), '80')
    await user.click(screen.getByRole('button', { name: 'Save completion' }))
    expect(summary().getByText('80')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Undo completion' }))
    await user.click(screen.getByRole('button', { name: 'Clear completion' }))
    expect(summary().getByText('0 / 1')).toBeInTheDocument()
    expect(screen.queryByText('Review traversal')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Delete session' }))
    await user.click(screen.getByRole('button', { name: 'Close' }))
    expect(screen.getByRole('article', { name: 'Trees' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Delete session' }))
    await user.click(screen.getByRole('button', { name: 'Delete permanently' }))
    expect(summary().getByText('0 / 0')).toBeInTheDocument()
    const loaded = loadData()
    expect(loaded.status !== 'error' && loaded.data.sessions).toEqual([])
  })
  it('validates session fields and completion without saving invalid records', async () => {
    const user = userEvent.setup()
    renderPlanner()
    await user.click(screen.getByRole('button', { name: 'Add session' }))
    await user.type(screen.getByLabelText('Topic'), 'Cache')
    await user.clear(screen.getByLabelText('Planned minutes'))
    await user.type(screen.getByLabelText('Planned minutes'), '0')
    await user.type(screen.getByLabelText('Resource link (optional)'), 'javascript:alert(1)')
    await user.click(screen.getByRole('button', { name: 'Save session' }))
    expect(screen.getByLabelText('Planned minutes')).toHaveAttribute('aria-invalid', 'true')
    expect(screen.getByLabelText('Resource link (optional)')).toHaveAttribute('aria-invalid', 'true')
    expect(screen.queryByRole('article')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Close' }))
    await addSession()
    await user.click(screen.getByRole('button', { name: 'Mark complete' }))
    await user.click(screen.getByRole('button', { name: 'Save completion' }))
    expect(screen.getByLabelText('Confidence')).toHaveAttribute('aria-invalid', 'true')
  })
  it('changes availability, shows capacity warnings, resets defaults and navigates weeks', async () => {
    const user = userEvent.setup()
    renderPlanner()
    await addSession()
    const today = calendarDate(new Date())
    await user.click(screen.getByRole('button', { name: `Edit availability for ${today}` }))
    await user.clear(screen.getByLabelText('Available study minutes'))
    await user.click(screen.getByRole('button', { name: 'Save availability' }))
    expect(screen.getByText('Enter 0–1440 whole minutes.')).toBeInTheDocument()
    await user.type(screen.getByLabelText('Available study minutes'), '0')
    await user.click(screen.getByRole('button', { name: 'Save availability' }))
    expect(screen.getByText('60 min planned · 60 min over availability')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: `Edit availability for ${today}` }))
    await user.click(screen.getByRole('button', { name: 'Use default availability' }))
    await user.click(screen.getByRole('button', { name: 'Next week' }))
    expect(screen.queryByRole('article')).not.toBeInTheDocument()
    expect(screen.getByRole('region', { name: addDays(getWeekStart(today), 7) })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Previous week' }))
    expect(screen.getByRole('article', { name: 'Graphs' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'This week' }))
  })
})
